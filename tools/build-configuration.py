#!/usr/bin/env python3
"""Write CONFIGURATION.md: every authored text file of the bundle in one Markdown document.

Run it after changing any file; `--check` only reports whether CONFIGURATION.md is out of date
(exit status 1), which tests/test_generated.py uses.
"""
from pathlib import Path
import re
import sys

ROOT = Path(__file__).resolve().parent.parent
OUTPUT = ROOT / 'CONFIGURATION.md'

# Sections in reading order; each is a list of glob patterns relative to the bundle.
SECTIONS = [
    ['install.sh'],
    ['distro/**/*'],
    ['palette/palette.toml'],
    ['tools/*'],
    ['tests/*'],
    ['bin/*'],
    ['config/**/*'],
    ['apps/**/*'],
    ['share/color-schemes/*', 'share/icons/*/index.theme', 'share/kio/servicemenus/*', 'share/lia-files/actions/*', 'share/gtksourceview-5/styles/*'],
    ['system/**/*'],
    ['boot/grub/theme.txt', 'boot/refind/theme.conf', 'boot/plymouth/*.plymouth'],
]
# Generated data, binary assets and drawings (SVG), which stay files of their own.
SKIP = [
    re.compile(r'.*\.svg$'),
    re.compile(r'.*/layers\.js$'),
    re.compile(r'^system/usr/share/icons/Penumbra-Cursors/cursors/'),
]
LANGUAGES = {
    '.sh': 'bash', '.py': 'python', '.lua': 'lua', '.qml': 'qml', '.js': 'javascript', '.toml': 'toml',
    '.css': 'css', '.ini': 'ini', '.conf': 'ini', '.jsonc': 'jsonc', '.json': 'json', '.fish': 'fish',
    '.rasi': 'css', '.svg': 'xml', '.frag': 'glsl', '.service': 'ini', '.desktop': 'ini', '.theme': 'ini',
    '.colors': 'ini', '.plymouth': 'ini', '.txt': 'text', '.tmTheme': 'xml', '.xml': 'xml',
    '.vsixmanifest': 'xml', '.yml': 'yaml', '.gitconfig': 'ini',
}

INTRO = '''# Complete Penumbra configuration

Every authored text file of the bundle: the installer, the palette, build tools and tests, helper
scripts, configuration and login screen. Generated by `tools/build-configuration.py`; the files
themselves are the source, so edit those and run it again. Images and drawings (the wallpaper and
icon SVGs), compiled cursors and shaders, and the animated wallpapers' generated `layers.js` are
only in the bundle.
'''


def text_of(path):
    """The file's text, or None for binary files."""
    data = path.read_bytes()
    if b'\0' in data:
        return None
    try:
        return data.decode('utf-8')
    except UnicodeDecodeError:
        return None


def language(path, text):
    if path.suffix in LANGUAGES:
        return LANGUAGES[path.suffix]
    first = text.split('\n', 1)[0]
    if first.startswith('#!'):
        return 'python' if 'python' in first else 'bash'
    return 'text' if path.suffix == '' else ''


def files():
    seen = set()
    for patterns in SECTIONS:
        found = set()
        for pattern in patterns:
            found.update(p for p in ROOT.glob(pattern) if p.is_file())
        for path in sorted(found):
            rel = path.relative_to(ROOT).as_posix()
            if rel in seen or any(skip.match(rel) for skip in SKIP):
                continue
            seen.add(rel)
            yield rel, path


def build():
    parts = [INTRO]
    for rel, path in files():
        text = text_of(path)
        if text is None:
            continue
        longest = max((len(run) for run in re.findall(r'`+', text)), default=0)
        fence = '`' * max(3, longest + 1)
        parts.append(f'\n## `{rel}`\n\n{fence}{language(path, text)}\n{text.rstrip(chr(10))}\n{fence}\n')
    return ''.join(parts)


def main():
    text = build()
    if '--check' in sys.argv[1:]:
        current = OUTPUT.read_text() if OUTPUT.exists() else ''
        if current != text:
            print('out of date: CONFIGURATION.md (run tools/build-configuration.py)')
            return 1
        return 0
    OUTPUT.write_text(text)
    print(f'wrote {OUTPUT.relative_to(ROOT)} ({len(text) // 1024} KiB)')
    return 0


if __name__ == '__main__':
    sys.exit(main())
